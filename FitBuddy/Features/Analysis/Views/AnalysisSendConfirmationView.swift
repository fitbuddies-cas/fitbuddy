import SwiftUI

/// The sheet between "Analyze with AI" and the transfer (US-3 AC12, #268):
/// what leaves the device, who receives it and in which order, on whose
/// contract, and that none of it is medical advice — then a checkbox the
/// user has to tick before "Send & analyze" does anything.
///
/// A sheet and not an alert: an alert has no room for a list, a link and a
/// checkbox. Styled like the consent screen it extends (`FBCard`,
/// `FBInfoRow`, accent toggle and button), because it makes the same kind of
/// promise at the moment it matters — where the recommendation is actually
/// requested, not only in onboarding.
///
/// Renders `AnalysisSendConfirmationViewModel` and nothing else: the
/// recipients, the checkbox and the proof live there.
struct AnalysisSendConfirmationView: View {
    @ObservedObject var viewModel: AnalysisSendConfirmationViewModel
    /// "Send & analyze" — `AnalysisViewModel.confirmSend()`.
    let onConfirm: () -> Void
    /// "Cancel", and the swipe down — `AnalysisViewModel.cancelSendConfirmation()`.
    let onCancel: () -> Void

    var body: some View {
        NavigationStack {
            ScrollView {
                VStack(alignment: .leading, spacing: 20) {
                    header
                    FBCard {
                        VStack(alignment: .leading, spacing: 20) {
                            whatIsSent
                            Divider().overlay(Color.fbDivider)
                            recipients
                            Divider().overlay(Color.fbDivider)
                            FBInfoRow(
                                icon: "person.text.rectangle",
                                title: "Your own contract",
                                text: """
                                These are health data. They are sent under your own API \
                                contract with the provider — you are their customer, not \
                                FitBuddy.
                                """
                            )
                            Divider().overlay(Color.fbDivider)
                            FBInfoRow(
                                icon: "cross.case",
                                title: "Not medical advice",
                                text: """
                                FitBuddy is not a medical device and gives no medical advice. \
                                The recommendation is generated by an AI and may be wrong. \
                                You act on it at your own risk. The FitBuddy team is not \
                                liable for the recommendation or for how the provider \
                                processes your data.
                                """
                            )
                        }
                    }
                    privacyLink
                    confirmationToggle
                    sendButton
                }
                .padding()
            }
            .background(Color.fbBackground)
            .navigationTitle("Before sending")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    Button("Cancel", action: onCancel)
                        .accessibilityIdentifier(AccessibilityID.SendConfirmation.cancelButton)
                }
            }
        }
        .accessibilityIdentifier(AccessibilityID.SendConfirmation.sheet)
        // Fresh on every opening (design rule of #268): the view model is
        // built per opening by `AnalysisViewModel.requestStart()`, and the
        // recipient list is read when the sheet appears rather than cached,
        // because a key added or removed in Settings changes who receives
        // the data.
        .task { await viewModel.load() }
    }

    private var header: some View {
        Text("Please check what this analysis sends, and to whom, before it leaves your device.")
            .font(.subheadline)
            .foregroundStyle(Color.fbInkSecondary)
    }

    /// The categories, as a list rather than a paragraph: the user is asked
    /// to confirm each of them, and a paragraph hides the fourth.
    private var whatIsSent: some View {
        HStack(alignment: .top, spacing: 12) {
            Image(systemName: "arrow.up.circle")
                .font(.title3)
                .foregroundStyle(Color.fbAccent)
                .frame(width: 28)
            VStack(alignment: .leading, spacing: 6) {
                Text("What will be sent")
                    .font(.fbTitle)
                    .foregroundStyle(Color.fbInk)
                ForEach(AnalysisSendConfirmationViewModel.sentDataCategories, id: \.self) { category in
                    bullet(category)
                }
                Text(AnalysisSendConfirmationViewModel.notSentNote)
                    .font(.subheadline.weight(.medium))
                    .foregroundStyle(Color.fbInk)
                    .padding(.top, 2)
            }
        }
    }

    /// The recipients in fallback order, numbered, with where each one
    /// processes the data — and the one sentence that explains why there
    /// can be more than one.
    private var recipients: some View {
        HStack(alignment: .top, spacing: 12) {
            Image(systemName: "globe")
                .font(.title3)
                .foregroundStyle(Color.fbAccent)
                .frame(width: 28)
            VStack(alignment: .leading, spacing: 6) {
                Text("Recipients")
                    .font(.fbTitle)
                    .foregroundStyle(Color.fbInk)
                recipientList
            }
        }
        .accessibilityElement(children: .combine)
        .accessibilityIdentifier(AccessibilityID.SendConfirmation.recipients)
    }

    @ViewBuilder
    private var recipientList: some View {
        if viewModel.isLoadingProviders {
            Text("Checking which providers you have connected…")
                .font(.subheadline)
                .foregroundStyle(Color.fbInkSecondary)
        } else if viewModel.couldNotReadProviders {
            Text("""
            Your provider keys could not be read right now, so the recipients \
            cannot be listed. Nothing is sent until they can.
            """)
            .font(.subheadline)
            .foregroundStyle(Color.fbRed)
        } else if viewModel.providers.isEmpty {
            Text("""
            No AI provider key is stored yet. Nothing can be sent until you add \
            one in Settings.
            """)
            .font(.subheadline)
            .foregroundStyle(Color.fbInkSecondary)
        } else {
            ForEach(Array(viewModel.providers.enumerated()), id: \.element) { index, provider in
                recipientRow(position: index + 1, provider: provider)
            }
            Text("The first provider answers; if it fails, the next one receives the same data.")
                .font(.subheadline)
                .foregroundStyle(Color.fbInkSecondary)
                .padding(.top, 2)
        }
    }

    /// `"1. Anthropic (Claude) · USA"`, and the contracting entity under it
    /// where it differs from the company that processes the data (US-4 AC4).
    private func recipientRow(position: Int, provider: LLMProvider) -> some View {
        VStack(alignment: .leading, spacing: 2) {
            Text("\(position). \(provider.recipientName) · \(provider.processingRegion)")
                .font(.subheadline.weight(.medium))
                .foregroundStyle(Color.fbInk)
            if let entity = provider.contractingEntity {
                Text("Your contract: \(entity)")
                    .font(.footnote)
                    .foregroundStyle(Color.fbMuted)
            }
        }
    }

    private func bullet(_ text: String) -> some View {
        HStack(alignment: .top, spacing: 6) {
            Text("•")
            Text(text)
        }
        .font(.subheadline)
        .foregroundStyle(Color.fbInkSecondary)
    }

    /// Pushed inside the sheet's own stack, so the statement opens over the
    /// sheet and "Back" returns to the checkbox rather than to the analysis
    /// screen.
    private var privacyLink: some View {
        NavigationLink {
            PrivacyPolicyView()
        } label: {
            Label("Privacy statement", systemImage: "doc.text")
                .font(.subheadline)
                .foregroundStyle(Color.fbAccent)
        }
        .accessibilityIdentifier(AccessibilityID.SendConfirmation.privacyLink)
    }

    private var confirmationToggle: some View {
        Toggle(isOn: $viewModel.hasConfirmedCheckbox) {
            Text("""
            I understand that my health data will be sent to the providers \
            listed above, and I do this on my own responsibility.
            """)
            .font(.subheadline)
            .foregroundStyle(Color.fbInk)
        }
        .tint(.fbAccent)
        .accessibilityIdentifier(AccessibilityID.SendConfirmation.checkbox)
    }

    private var sendButton: some View {
        Button("Send & analyze", action: onConfirm)
            .buttonStyle(.fb(.accent))
            .disabled(!viewModel.canSend)
            .accessibilityIdentifier(AccessibilityID.SendConfirmation.sendButton)
    }
}

