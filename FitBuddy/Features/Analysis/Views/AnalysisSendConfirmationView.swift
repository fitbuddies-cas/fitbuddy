/// In-memory keys for the previews: `read` answers for the listed slots.
private struct PreviewKeychain: KeychainStoring {
    let keys: Set<KeychainKey>

    func save(_ value: String, for key: KeychainKey) throws {}
    func read(_ key: KeychainKey) throws -> String? { keys.contains(key) ? "preview-key" : nil }
    func delete(_ key: KeychainKey) throws {}
    func exists(_ key: KeychainKey) throws -> Bool { keys.contains(key) }
}

/// A priority store over its own defaults suite, so a preview never reads or
/// writes the host's real order.
private func makePreviewPriorityStore(order: [LLMProvider]) -> LLMPriorityStore {
    let defaults = UserDefaults(suiteName: "fitbuddy.preview.sendConfirmation") ?? .standard
    defaults.set(order.map(\.rawValue), forKey: LLMPriorityStore.priorityOrderKey)
    return LLMPriorityStore(defaults: defaults)
}
